/*
 * 題庫詳解：依題目在題庫中的位置，為每一題加上詳解（item.exp）。
 * 出題時 quiz.js 會把 exp 一併帶出，答錯或看答案時顯示。
 * 涵蓋：英文題庫、日文題庫、數學 9 年級（一元二次方程式、三角比）。
 */
(function () {
  "use strict";

  function setExp(bank, texts) {
    texts.forEach(function (t, i) {
      if (bank[i] && t) bank[i].exp = t;
    });
  }
  function unitBank(unitId) {
    var found = null;
    window.SUBJECTS.forEach(function (s) {
      Object.keys(s.chapters).forEach(function (g) {
        s.chapters[g].forEach(function (ch) {
          ch.units.forEach(function (u) { if (u.id === unitId) found = u.bank; });
        });
      });
    });
    return found;
  }

  /* ---------- 英文題庫（與 content-lang.js 的順序一致） ---------- */
  setExp(window.LANG_BANK.en, [
    "主詞是 I，be 動詞用 am。記住：I 用 am；you、we、they 用 are；he、she、it 用 is。",
    "主詞 She 是第三人稱單數，be 動詞用 is。",
    "主詞 We 是複數（我們），be 動詞用 are。",
    "every day 表示現在的習慣，主詞 He 是第三人稱單數，動詞要加 es：go → goes。",
    "now 表示「正在」，現在進行式是 be 動詞 + 動詞 ing。They 是複數，用 are。",
    "Yesterday 是過去的時間，要用過去式。go 的過去式是 went（不規則動詞，需要背）。",
    "There be 句型的 be 動詞看後面的名詞：three cats 是複數，所以用 are。",
    "since 後面接「時間點」（2010 是年份），for 後面接「一段時間」。這裡用 since。",
    "yesterday 是過去的時間，被動語態的 be 動詞要用過去式 was。",
    "兩者比較用「比較級 + than」。tall 是單音節字，加 er 變成 taller。",
    "現在完成式是 have + 過去分詞。see 的過去分詞是 seen（不是 saw）。",
    "被動語態是 be 動詞 + 過去分詞。English 是單數名詞，所以用 is。",
    "這是真實條件句：if 子句用現在式，主要子句用 will（未來）。",
    "被動語態用 was + 過去分詞。write 的過去分詞是 written。",
    "neither...nor... 的 be 動詞依「靠近的那個主詞」決定。his friends 是複數，用 are。",
    "Had I known 是 If I had known 的倒裝，屬於與過去事實相反的假設，主要子句用 would have + 過去分詞。",
    "The more..., the more...（越...越...）句型，後面要用 the better。",
    "be said to be ... 是「據說是...」的固定句型，要用 to be。"
  ]);

  /* ---------- 日文題庫（與 content-lang.js 的順序一致） ---------- */
  setExp(window.LANG_BANK.ja, [
    "「さ」在五十音的「さ行」，羅馬拼音是 sa。",
    "「ありがとう」是感謝的意思，較有禮貌的說法是「ありがとうございます」。",
    "「いち」讀作 ichi，是數字 1。",
    "「ねこ」（猫）是貓。",
    "「いぬ」（犬）是狗。",
    "「学生」讀作「がくせい」（gakusei），意思是學生。",
    "「先生」讀作「せんせい」（sensei），意思是老師。",
    "「わたし」是「我」，是最常用的第一人稱。",
    "「おいしい」是「好吃、美味」，屬於い形容詞。",
    "「食べる」是「吃」，屬於一段動詞（去掉る加ます：食べます）。",
    "「行く」是五段動詞，但它是特例，て形是「行って」，不是「行いて」。",
    "「見る」是一段動詞，去掉「る」加「て」，得到「見て」。",
    "「書きます」去掉ます，變成い段（き），加上「く」，得到辭書形「書く」。",
    "い形容詞否定形：去掉「い」，加上「くない」，所以「高い」變成「高くない」。",
    "「もし」表示「如果、假如」，後面常接條件句（〜ば、〜たら）。",
    "〜ています表示「正在進行」，「読んでいます」就是「正在閱讀」。",
    "「食べさせられる」是「使役被動」：使役（させる）加上被動（られる）。",
    "「わたしは」的「は」是主題助詞；「台湾人」是台灣人；「です」表示判斷「是」。整句是「我是台灣人」。"
  ]);

  /* ---------- 數學 9 年級：二次方程式（9-3）---------- */
  setExp(unitBank("math-9-3"), [
    "x² = 49，開平方得 x = ±7，正數解是 7。",
    "x² = 81，開平方得 x = ±9，正數解是 9。",
    "x² = 144，開平方得 x = ±12，正數解是 12。",
    "45 × 45 = 2025，所以 x = ±45，正數解是 45。"
  ]);

  /* ---------- 數學 9 年級：一元二次方程式（9-6）---------- */
  setExp(unitBank("math-9-6"), [
    "兩數相乘等於 0，則其中一個為 0：x − 2 = 0 或 x + 3 = 0，得 x = 2 或 x = −3。較大的是 2。",
    "韋達定理：兩根之和 = −(一次項係數) ÷ 二次項係數 = −(−5) ÷ 1 = 5。也可以因式分解成 (x − 2)(x − 3) = 0，兩根是 2 與 3，和為 5。",
    "移項得 x² = 9，開平方得 x = ±3，正數解是 3。",
    "因式分解：x² − x − 12 = (x − 4)(x + 3) = 0，得 x = 4 或 x = −3。較小的是 −3。"
  ]);

  /* ---------- 數學 9 年級：三角比（9-5）---------- */
  setExp(unitBank("math-9-5"), [
    "正弦的定義：sin A = 對邊 ÷ 斜邊。",
    "45° 的直角等腰三角形，對邊與鄰邊相等，tan 45° = 對邊 ÷ 鄰邊 = 1。",
    "30°-60°-90° 特殊三角形中，cos 60° = 鄰邊 ÷ 斜邊 = 1/2 = 0.5。",
    "3-4-5 直角三角形，斜邊為 5。tan A = 對邊 ÷ 鄰邊 = 3 ÷ 4 = 3/4。"
  ]);
})();
